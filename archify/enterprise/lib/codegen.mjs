function sql(model) {
  const types = classifierModel(model);
  const entities = types.filter((type) => type.kind === 'entity');
  if (!entities.length) return [];
  const enums = types.filter((type) => type.kind === 'enum');
  const lines = [header(model, '--'), '-- Dialect: PostgreSQL.', ''];
  const q = (name) => `"${name}"`;
  const foreign = new Map(entities.map((entity) => [entity.id, []]));
  for (const rel of model.relationships || []) {
    const from = entities.find((entity) => entity.id === rel.from); const to = entities.find((entity) => entity.id === rel.to);
    if (!from || !to || !['composition', 'aggregation', 'association'].includes(rel.kind)) continue;
    // The key lives on the "many" end; a to-one association keeps it on the source.
    const [holder, target] = many(rel.toMult) || rel.kind === 'composition' ? [to, from] : [from, to];
    // A to-one key takes the role name; repeated keys to one table stay distinct.
    const keys = foreign.get(holder.id);
    const stem = holder === from && rel.role ? snake(rel.role) : snake(target.name);
    let column = `${stem}_id`;
    if (keys.some((key) => key.column === column) && rel.role && holder !== from) column = `${stem}_${snake(rel.role)}_id`;
    for (let index = 2; keys.some((key) => key.column === column); index += 1) column = `${stem}_${index}_id`;
    keys.push({ column, target, required: rel.kind === 'composition' || !/^0/.test(String(holder === to ? rel.fromMult : rel.toMult) || ''), cascade: rel.kind === 'composition' });
  }
  for (const type of enums) {
    if (entities.some((entity) => entity.fields.some((item) => parseType(item.type).base === type.name))) {
      lines.push(`CREATE TYPE ${q(snake(type.name))} AS ENUM (${literals(type).map((name) => `'${name}'`).join(', ')});`, '');
    }
  }
  const constraints = [];
  for (const entity of entities) {
    const table = snake(entity.name);
    const columns = [];
    const fields = entity.fields.filter((item) => item.source === 'attribute');
    if (!fields.some((item) => item.pk)) columns.push('  "id" UUID PRIMARY KEY');
    for (const item of fields) {
      const { base } = parseType(item.type);
      const enumType = enums.find((type) => type.name === base);
      const sqlType = enumType ? q(snake(enumType.name)) : PRIMITIVES[base.toLowerCase()]?.sql || 'TEXT';
      columns.push(`  ${q(snake(item.name))} ${sqlType}${item.pk ? ' PRIMARY KEY' : item.nullable ? '' : ' NOT NULL'}${item.unique ? ' UNIQUE' : ''}`);
    }
    for (const key of foreign.get(entity.id)) {
      // The key column has the type of the primary key it references.
      const targetPk = key.target.fields.find((item) => item.source === 'attribute' && item.pk);
      const keyType = targetPk ? PRIMITIVES[parseType(targetPk.type).base.toLowerCase()]?.sql || 'TEXT' : 'UUID';
      if (!fields.some((item) => snake(item.name) === key.column)) columns.push(`  ${q(key.column)} ${keyType}${key.required ? ' NOT NULL' : ''}`);
      const targetKey = targetPk?.name || 'id';
      constraints.push(`ALTER TABLE ${q(table)} ADD CONSTRAINT ${q(`fk_${table}_${key.column}`)} FOREIGN KEY (${q(key.column)}) REFERENCES ${q(snake(key.target.name))} (${q(snake(targetKey))})${key.cascade ? ' ON DELETE CASCADE' : ''};`);
      constraints.push(`CREATE INDEX ${q(`idx_${table}_${key.column}`)} ON ${q(table)} (${q(key.column)});`);
    }
    lines.push(...(entity.doc ? [`-- ${entity.doc}`] : []), `CREATE TABLE ${q(table)} (`, columns.join(',\n'), ');', '');
  }
  lines.push(...constraints);
  return [{ path: 'sql/schema.sql', content: `${lines.join('\n').trimEnd()}\n` }];
}

// ---- OpenAPI --------------------------------------------------------------

function yaml(value, indent = 0) {
  const pad = '  '.repeat(indent);
  const scalar = (item) => (typeof item === 'string' ? (/^[A-Za-z][A-Za-z0-9 _./-]*$/.test(item) && !/^(true|false|null|yes|no|on|off)$/i.test(item) ? item : JSON.stringify(item)) : String(item));
  if (Array.isArray(value)) return value.length ? value.map((item) => (item && typeof item === 'object' ? `${pad}-\n${yaml(item, indent + 1)}` : `${pad}- ${scalar(item)}`)).join('\n') : `${pad}[]`;
  return Object.entries(value).map(([key, item]) => {
    const name = /^[A-Za-z_][A-Za-z0-9_-]*$/.test(key) ? key : JSON.stringify(key);
    if (item && typeof item === 'object') return Object.keys(item).length ? `${pad}${name}:\n${yaml(item, indent + 1)}` : `${pad}${name}: ${Array.isArray(item) ? '[]' : '{}'}`;
    return `${pad}${name}: ${scalar(item)}`;
  }).join('\n');
}

function openapi(model) {
  const interfaces = (model.elements || []).filter((element) => Array.isArray(element.operations) && element.operations.length);
  if (!interfaces.length) return [];
  const filePaths = new Set();
  const types = classifierModel(model);
  const schemaRef = (name) => (types.some((type) => type.name === name) ? { $ref: `#/components/schemas/${name}` } : { type: 'object' });
  const property = (item) => {
    const { base, many: isMany } = parseType(item.type);
    const primitive = PRIMITIVES[base.toLowerCase()];
    const schema = types.some((type) => type.name === base) ? { $ref: `#/components/schemas/${base}` } : primitive ? { ...primitive.oas } : { type: 'string' };
    return isMany ? { type: 'array', items: schema } : schema;
  };
  const schemas = {};
  for (const type of types) {
    if (type.kind === 'enum') schemas[type.name] = { type: 'string', enum: literals(type) };
    else if (['entity', 'record'].includes(type.kind)) {
      const required = type.fields.filter((item) => !item.nullable && !parseType(item.type).many).map((item) => item.name);
      schemas[type.name] = { type: 'object', ...(required.length ? { required } : {}), properties: Object.fromEntries(type.fields.map((item) => [item.name, property(item)])) };
    }
  }
  return interfaces.map((element) => {
    const paths = {};
    for (const operation of element.operations) {
      const method = String(operation.method || 'get').toLowerCase();
      const parameters = [...String(operation.path).matchAll(/\{([^}]+)\}/g)].map((match) => ({ name: match[1], in: 'path', required: true, schema: { type: 'string' } }));
      paths[operation.path] = { ...(paths[operation.path] || {}), [method]: {
        operationId: camel(`${method} ${String(operation.path).replace(/[{}]/g, '')}`),
        summary: operation.summary || `${method.toUpperCase()} ${operation.path}`,
        ...(parameters.length ? { parameters } : {}),
        ...(operation.request ? { requestBody: { required: true, content: { 'application/json': { schema: schemaRef(operation.request) } } } } : {}),
        responses: { [method === 'post' ? '201' : '200']: { description: 'Success', ...(operation.response ? { content: { 'application/json': { schema: schemaRef(operation.response) } } } : {}) } },
      } };
    }
    const doc = { openapi: '3.1.0', info: { title: element.label, version: '0.1.0', description: element.doc || `Generated from the ${model.meta?.title || 'enterprise'} model.` }, paths, components: { schemas } };
    return { path: `openapi/${uniqueName(kebab, element.label, element.id, filePaths)}.yaml`, content: `${header(model, '#')}\n${yaml(doc)}\n` };
  });
}

// ---- State machines -------------------------------------------------------

function statemachine(model) {
  const { elements } = indexModel(model);
  const machines = new Set(); const paths = new Set();
  return (model.views || []).filter((view) => view.type === 'state').map((view) => {
    const name = uniqueName(pascal, view.title, view.id, machines);
    const rels = viewRelationships(model, view).filter((rel) => rel.kind === 'transition');
    const states = (view.nodes || []).map((node) => elements.get(node.ref)).filter((element) => element && element.kind === 'state');
    const stateIds = new Set(states.map((state) => state.id));
    const stateNames = new Set();
    const keys = new Map(states.map((state) => [state.id, uniqueName(screaming, state.label, state.id, stateNames)]));
    const key = (element) => keys.get(element.id);
    const initial = rels.find((rel) => elements.get(rel.from)?.kind === 'initial' && stateIds.has(rel.to));
    const finals = rels.filter((rel) => elements.get(rel.to)?.kind === 'final' && stateIds.has(rel.from)).map((rel) => key(elements.get(rel.from)));
    const table = new Map(states.map((state) => [key(state), []]));
    for (const rel of rels) {
      if (!stateIds.has(rel.from) || !stateIds.has(rel.to)) continue;
      table.get(key(elements.get(rel.from))).push({ event: screaming(rel.label || `to ${key(elements.get(rel.to))}`), to: key(elements.get(rel.to)), guard: rel.guard });
    }
    // One state may leave on the same event under different guards. An object
    // key can hold one target, so those events are named by their target too.
    for (const entries of table.values()) {
      const seen = new Set();
      for (const entry of entries) {
        const repeated = entries.filter((other) => other.event === entry.event).length > 1;
        let event = repeated ? `${entry.event}_TO_${entry.to}` : entry.event;
        for (let index = 2; seen.has(event); index += 1) event = `${entry.event}_TO_${entry.to}_${index}`;
        seen.add(event);
        entry.key = event;
      }
    }
    for (const entries of table.values()) for (const entry of entries) entry.event = entry.key;
    const events = [...new Set([...table.values()].flat().map((entry) => entry.event))];
    const union = (items) => (items.length ? items.map((item) => `'${item}'`).join(' | ') : 'never');
    const lines = [header(model, '//'), '', `export type ${name}State = ${union([...table.keys()])};`, `export type ${name}Event = ${union(events)};`, '',
      `export const ${camel(name)}Initial: ${name}State = '${initial ? key(elements.get(initial.to)) : [...table.keys()][0]}';`,
      `export const ${camel(name)}Final: readonly ${name}State[] = [${[...new Set(finals)].map((item) => `'${item}'`).join(', ')}];`, '',
      `export const ${camel(name)}Transitions: Record<${name}State, Partial<Record<${name}Event, ${name}State>>> = {`,
      ...[...table.entries()].map(([state, entries]) => `  ${state}: {${entries.length ? ` ${entries.map((entry) => `${entry.event}: '${entry.to}'`).join(', ')} ` : ''}},${entries.some((entry) => entry.guard) ? ` // guards: ${entries.filter((entry) => entry.guard).map((entry) => `${entry.event} when ${String(entry.guard).replace(/[\r\n]+/g, ' ')}`).join('; ')}` : ''}`), '};', '',
      `export function ${camel(name)}Next(state: ${name}State, event: ${name}Event): ${name}State {`,
      `  const next = ${camel(name)}Transitions[state][event];`,
      '  if (!next) throw new Error(`Illegal transition: ${state} on ${event}`);', '  return next;', '}'];
    return { path: `statemachine/${uniqueName(kebab, view.title, view.id, paths)}.ts`, content: `${lines.join('\n')}\n` };
  });
}

// ---- BPMN 2.0 -------------------------------------------------------------

const BPMN_TAGS = {
  'start-event': 'startEvent', 'end-event': 'endEvent', 'intermediate-event': 'intermediateCatchEvent', subprocess: 'subProcess',
  'exclusive-gateway': 'exclusiveGateway', 'parallel-gateway': 'parallelGateway', 'inclusive-gateway': 'inclusiveGateway', 'data-store': 'dataStoreReference',
  initial: 'startEvent', final: 'endEvent', action: 'task', decision: 'exclusiveGateway', merge: 'exclusiveGateway', fork: 'parallelGateway', join: 'parallelGateway',
};
const BPMN_TASKS = { user: 'userTask', service: 'serviceTask', script: 'scriptTask', send: 'sendTask', receive: 'receiveTask', manual: 'manualTask' };
const BPMN_EVENT_DEFS = { message: 'messageEventDefinition', timer: 'timerEventDefinition', error: 'errorEventDefinition', signal: 'signalEventDefinition' };

function bpmn(model) {
  const { elements } = indexModel(model);
  const paths = new Set();
  return (model.views || []).filter((view) => view.type === 'bpmn' || view.type === 'activity').map((view) => {
    const layout = layoutView(model, view);
    const processId = `Process_${view.id}`;
    const flows = layout.edges.filter((edge) => ['sequence-flow', 'control-flow'].includes(edge.rel.kind));
    const lanes = (view.groups || []).filter((group) => group.kind === 'lane');
    const out = ['<?xml version="1.0" encoding="UTF-8"?>', `<!-- ${header(model, '').trim()} -->`,
      `<bpmn:definitions xmlns:bpmn="http://www.omg.org/spec/BPMN/20100524/MODEL" xmlns:bpmndi="http://www.omg.org/spec/BPMN/20100524/DI" xmlns:dc="http://www.omg.org/spec/DD/20100524/DC" xmlns:di="http://www.omg.org/spec/DD/20100524/DI" id="Definitions_${view.id}" targetNamespace="https://archify.dev/enterprise" exporter="Archify Enterprise">`];
    if (lanes.length) out.push(`  <bpmn:collaboration id="Collaboration_${view.id}">`, `    <bpmn:participant id="Participant_${view.id}" name="${xml(view.title)}" processRef="${processId}"/>`, '  </bpmn:collaboration>');
    out.push(`  <bpmn:process id="${processId}" name="${xml(view.title)}" isExecutable="false">`);
    if (lanes.length) {
      out.push(`    <bpmn:laneSet id="LaneSet_${view.id}">`);
      lanes.forEach((lane, index) => out.push(`      <bpmn:lane id="Lane_${view.id}_${index}" name="${xml(lane.label)}">`, ...lane.wraps.map((ref) => `        <bpmn:flowNodeRef>${ref}</bpmn:flowNodeRef>`), '      </bpmn:lane>'));
      out.push('    </bpmn:laneSet>');
    }
    for (const node of layout.nodes) {
      const element = elements.get(node.id);
      const tag = element.kind === 'task' ? BPMN_TASKS[element.taskType] || 'task' : BPMN_TAGS[element.kind] || 'task';
      const incoming = flows.filter((edge) => edge.to === node.id).map((edge) => `      <bpmn:incoming>${edge.id}</bpmn:incoming>`);
      const outgoing = flows.filter((edge) => edge.from === node.id).map((edge) => `      <bpmn:outgoing>${edge.id}</bpmn:outgoing>`);
      const definition = tag.endsWith('Event') && BPMN_EVENT_DEFS[element.trigger] ? [`      <bpmn:${BPMN_EVENT_DEFS[element.trigger]}/>`] : [];
      out.push(`    <bpmn:${tag} id="${node.id}"${element.label ? ` name="${xml(element.label)}"` : ''}>`, ...incoming, ...outgoing, ...definition, `    </bpmn:${tag}>`);
    }
    for (const edge of flows) {
      const name = edge.rel.label || (edge.rel.guard && edge.rel.guard !== 'else' ? edge.rel.guard : '');
      out.push(`    <bpmn:sequenceFlow id="${edge.id}" sourceRef="${edge.from}" targetRef="${edge.to}"${name ? ` name="${xml(name)}"` : ''}/>`);
    }
    out.push('  </bpmn:process>', `  <bpmndi:BPMNDiagram id="Diagram_${view.id}">`, `    <bpmndi:BPMNPlane id="Plane_${view.id}" bpmnElement="${lanes.length ? `Collaboration_${view.id}` : processId}">`);
    const bounds = (id, rect, extra = '') => out.push(`      <bpmndi:BPMNShape id="${id}_di" bpmnElement="${id}"${extra}>`, `        <dc:Bounds x="${Math.round(rect.x)}" y="${Math.round(rect.y)}" width="${Math.round(rect.w)}" height="${Math.round(rect.h)}"/>`, '      </bpmndi:BPMNShape>');
    if (lanes.length) {
      const frames = layout.groups.filter((group) => group.strip);
      const x0 = Math.min(...frames.map((frame) => frame.x)) - 30; const y0 = Math.min(...frames.map((frame) => frame.y));
      const x1 = Math.max(...frames.map((frame) => frame.x + frame.w)); const y1 = Math.max(...frames.map((frame) => frame.y + frame.h));
      bounds(`Participant_${view.id}`, { x: x0, y: y0, w: x1 - x0, h: y1 - y0 }, ' isHorizontal="true"');
      lanes.forEach((lane, index) => { const frame = frames.find((entry) => entry.label === lane.label); bounds(`Lane_${view.id}_${index}`, { x: x0 + 30, y: frame.y, w: x1 - x0 - 30, h: frame.h }, ' isHorizontal="true"'); });
    }
    for (const node of layout.nodes) bounds(node.id, node, KINDS[node.kind].shape === 'gateway' ? ' isMarkerVisible="true"' : '');
    for (const edge of flows) out.push(`      <bpmndi:BPMNEdge id="${edge.id}_di" bpmnElement="${edge.id}">`, ...edge.points.map(([x, y]) => `        <di:waypoint x="${Math.round(x)}" y="${Math.round(y)}"/>`), '      </bpmndi:BPMNEdge>');
    out.push('    </bpmndi:BPMNPlane>', '  </bpmndi:BPMNDiagram>', '</bpmn:definitions>');
    return { path: `bpmn/${uniqueName(kebab, view.title, view.id, paths)}.bpmn`, content: `${out.join('\n')}\n` };
  });
}

// ---- ArchiMate Model Exchange File Format ---------------------------------

const ARCHIMATE_RELATIONS = { composition: 'Composition', aggregation: 'Aggregation', assignment: 'Assignment', realization: 'Realization', serving: 'Serving', access: 'Access', influence: 'Influence', triggering: 'Triggering', flow: 'Flow', specialization: 'Specialization', association: 'Association' };
const archimateType = (kind) => ({ node: 'Node', device: 'Device', artifact: 'Artifact', contract: 'Contract', product: 'Product' }[kind] || pascal(kind));

function archimate(model) {
  const elements = (model.elements || []).filter((element) => KINDS[element.kind]?.family === 'archimate');
  if (!elements.length) return [];
  const ids = new Set(elements.map((element) => element.id));
  const relationships = (model.relationships || []).filter((rel) => ids.has(rel.from) && ids.has(rel.to) && ARCHIMATE_RELATIONS[rel.kind]);
  const relIds = new Set(relationships.map((rel) => rel.id));
  const out = ['<?xml version="1.0" encoding="UTF-8"?>', `<!-- ${header(model, '').trim()} -->`,
    '<model xmlns="http://www.opengroup.org/xsd/archimate/3.0/" xmlns:xsi="http://www.w3.org/2001/XMLSchema-instance" xsi:schemaLocation="http://www.opengroup.org/xsd/archimate/3.0/ http://www.opengroup.org/xsd/archimate/3.1/archimate3_Diagram.xsd" identifier="id-model">',
    `  <name xml:lang="en">${xml(model.meta?.title)}</name>`, '  <elements>'];
  for (const element of elements) {
    out.push(`    <element identifier="id-${element.id}" xsi:type="${archimateType(element.kind)}">`, `      <name xml:lang="en">${xml(element.label)}</name>`, ...(element.doc ? [`      <documentation xml:lang="en">${xml(element.doc)}</documentation>`] : []), '    </element>');
  }
  out.push('  </elements>', '  <relationships>');
  for (const rel of relationships) {
    out.push(`    <relationship identifier="id-${rel.id}" source="id-${rel.from}" target="id-${rel.to}" xsi:type="${ARCHIMATE_RELATIONS[rel.kind]}">${rel.label ? `<name xml:lang="en">${xml(rel.label)}</name>` : ''}</relationship>`);
  }
  out.push('  </relationships>', '  <views>', '    <diagrams>');
  for (const view of (model.views || []).filter((entry) => entry.type === 'archimate')) {
    const layout = layoutView(model, view);
    out.push(`      <view identifier="id-${view.id}" xsi:type="Diagram">`, `        <name xml:lang="en">${xml(view.title)}</name>`);
    for (const node of layout.nodes.filter((entry) => ids.has(entry.id))) out.push(`        <node identifier="id-${view.id}-${node.id}" elementRef="id-${node.id}" xsi:type="Element" x="${Math.round(node.x)}" y="${Math.round(node.y)}" w="${Math.round(node.w)}" h="${Math.round(node.h)}"/>`);
    for (const edge of layout.edges.filter((entry) => relIds.has(entry.id))) out.push(`        <connection identifier="id-${view.id}-${edge.id}" relationshipRef="id-${edge.id}" xsi:type="Relationship" source="id-${view.id}-${edge.from}" target="id-${view.id}-${edge.to}"/>`);
    out.push('      </view>');
  }
  out.push('    </diagrams>', '  </views>', '</model>');
  return [{ path: `archimate/${kebab(model.meta?.title || 'model')}.archimate.xml`, content: `${out.join('\n')}\n` }];
}

const GENERATORS = { typescript, java, python, sql, openapi, statemachine, bpmn, archimate };

export function generateCode(model, target) {
  if (!GENERATORS[target]) throw new Error(`Unknown code target "${target}". Use one of: ${Object.keys(GENERATORS).join(', ')}.`);
  return GENERATORS[target](model);
}
