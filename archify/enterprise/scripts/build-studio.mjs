#!/usr/bin/env node
// Build the self-contained Enterprise Studio page: inline the library modules
// and the example model into studio/studio.source.html.
//
//   node enterprise/scripts/build-studio.mjs            write enterprise/studio.html
//   node enterprise/scripts/build-studio.mjs --check    fail if the committed page is stale
//   node enterprise/scripts/build-studio.mjs --fragment out.html
//                                                       write the page without the document
//                                                       wrapper, for hosts that add their own

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
// Dependency order: each module only imports from modules listed before it.
const MODULES = ['notation', 'model', 'layout', 'render', 'codegen', 'tasks', 'simulate', 'native'];

export function bundleModules() {
  const seen = new Map();
  const parts = MODULES.map((name) => {
    const source = fs.readFileSync(path.join(root, 'lib', `${name}.mjs`), 'utf8');
    const lines = source.split('\n').filter((line) => {
      if (!line.startsWith('import ')) return true;
      if (!/^import \{[^}]*\} from '\.\/[a-z]+\.mjs';$/.test(line)) throw new Error(`${name}.mjs: unsupported import for bundling: ${line}`);
      return false;
    }).map((line) => {
      if (/^export \{/.test(line) || /^export default/.test(line)) throw new Error(`${name}.mjs: only "export const" and "export function" can be bundled: ${line}`);
      return line.replace(/^export (?=(?:const|let|function|class) )/, '');
    });
    for (const line of lines) {
      const declared = line.match(/^(?:const|let|function|class) ([A-Za-z_$][\w$]*)/);
      if (!declared) continue;
      if (seen.has(declared[1])) throw new Error(`Top-level name "${declared[1]}" is declared in both ${seen.get(declared[1])}.mjs and ${name}.mjs; rename one so the modules can share a bundle.`);
      seen.set(declared[1], name);
    }
    return `// ---- lib/${name}.mjs ----\n${lines.join('\n').trim()}`;
  });
  return parts.join('\n\n');
}

export function buildStudio({ fragment = false } = {}) {
  const template = fs.readFileSync(path.join(root, 'studio', 'studio.source.html'), 'utf8');
  const example = JSON.parse(fs.readFileSync(path.join(root, 'examples', 'order-to-cash.enterprise.json'), 'utf8'));
  const bundle = bundleModules();
  if (/<\/script/i.test(bundle)) throw new Error('A library module contains "</script", which would end the inline script.');
  if (!template.includes('/*__BUNDLE__*/') || !template.includes('/*__EXAMPLE__*/null')) throw new Error('studio.source.html is missing a build placeholder.');
  const page = template
    .replace('/*__BUNDLE__*/', () => bundle)
    .replace('/*__EXAMPLE__*/null', () => JSON.stringify(example).replace(/</g, '\\u003c'));
  if (fragment) return page;
  return `<!doctype html>\n<html lang="en">\n<head>\n<meta charset="utf-8">\n<meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover">\n<!-- Generated by enterprise/scripts/build-studio.mjs. Edit enterprise/studio/studio.source.html and enterprise/lib instead. -->\n<style>body{margin:0}[hidden]{display:none!important}</style>\n</head>\n<body>\n${page}</body>\n</html>\n`;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const args = process.argv.slice(2);
  const target = path.join(root, 'studio.html');
  if (args[0] === '--fragment') {
    if (!args[1]) { console.error('--fragment needs an output path'); process.exit(2); }
    fs.writeFileSync(args[1], buildStudio({ fragment: true }));
    console.log(`wrote ${args[1]}`);
  } else if (args[0] === '--check') {
    const current = fs.existsSync(target) ? fs.readFileSync(target, 'utf8') : '';
    if (current !== buildStudio()) { console.error('enterprise/studio.html is stale. Run: node enterprise/scripts/build-studio.mjs'); process.exit(1); }
    console.log('enterprise/studio.html is up to date');
  } else {
    fs.writeFileSync(target, buildStudio());
    console.log(`wrote ${path.relative(process.cwd(), target)}`);
  }
}
